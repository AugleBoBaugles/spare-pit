-- Postgres inventory table schema (Supabase or self-hosted).
--
-- The server runs this automatically on startup if the table is missing.
-- To apply it by hand instead:
--   Supabase: open your project → SQL Editor → New Query, paste this file, click Run
--   Self-hosted: psql "$DATABASE_URL" -f server/db/supabase-schema.sql
--
-- Column naming: camelCase columns (itemImage, checkOutBy, lastUpdated) are quoted
-- so PostgreSQL preserves their case. The Supabase JS client and the frontend both
-- expect these exact names — do not rename them.

create table if not exists public.inventory (
  id            bigint generated by default as identity primary key,
  name          text        not null,
  type          text,
  area          text,
  location      text,
  status        text,
  quantity      integer,
  condition     text,
  "itemImage"   text,
  "checkOutBy"  text,
  "lastUpdated"   timestamptz default now(),
  tags            text,
  notes           text,
  "needsRestock"  integer     default 0
);
