-- Postgres schema (Supabase or self-hosted).
--
-- The server runs this automatically on every start; every statement is
-- "if not exists", so it only creates what is missing.
-- To apply it by hand instead:
--   Supabase: open your project → SQL Editor → New Query, paste this file, click Run
--   Self-hosted: psql "$DATABASE_URL" -f server/db/supabase-schema.sql
--
-- Column naming: camelCase columns (itemImage, checkOutBy, lastUpdated, areaId, locationId) are quoted
-- so PostgreSQL preserves their case. The frontend expects these exact names — do not rename them.

-- Areas are rooms or zones (e.g. "Machine Shop"). Each location belongs to at most one area.
create table if not exists public.areas (
  id    bigint generated by default as identity primary key,
  name  text not null
);
create unique index if not exists areas_name_lower_idx on public.areas (lower(name));

-- Locations are specific spots inside an area (e.g. "Tool Cabinet A").
-- "areaId" is null while a location is unassigned. Names only have to be unique within
-- their area (unassigned locations count as one group), so two areas can each have a
-- "Tool Cabinet A".
create table if not exists public.locations (
  id        bigint generated by default as identity primary key,
  name      text not null,
  "areaId"  bigint references public.areas(id) on delete set null
);
create unique index if not exists locations_area_name_lower_idx
  on public.locations (coalesce("areaId", 0), lower(name));

-- "locationId" points at one exact location; null means the item has no location.
create table if not exists public.inventory (
  id            bigint generated by default as identity primary key,
  name          text        not null,
  type          text,
  "locationId"  bigint      references public.locations(id) on delete set null,
  status        text,
  quantity      integer,
  condition     text,
  "itemImage"   text,
  "checkOutBy"  text,
  "lastUpdated"   timestamptz default now(),
  tags            text,
  notes           text,
  "needsRestock"  integer     default 0
);
